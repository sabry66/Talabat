import { chromium } from 'playwright';
const ROOT = new URL('..', import.meta.url).pathname.replace(/\/$/, '');
const SP = ROOT + '/out';
const B = 'http://127.0.0.1:8765/';
const b = await chromium.launch(); const errs = [];
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, serviceWorkers: 'block', isMobile: true, hasTouch: true });
await ctx.route(/fonts\.googleapis|tile\.openstreetmap|cdnjs/, r => r.abort());
await ctx.route('**/js/firebase-config.js', r => r.fulfill({ contentType: 'application/javascript', body: "export const firebaseConfig = { apiKey: '' }; export const useEmulators = false;" }));
const login = async (p, email) => { await p.waitForSelector('.auth-card'); await p.click(`[data-demo="${email}"]`); await p.click('#authForm button[type=submit]'); };
const a = await ctx.newPage(); a.on('pageerror', e => errs.push(e.message));
await a.goto(B + 'admin.html'); await login(a, 'admin@demo.com'); await a.waitForSelector('#tabs', { state: 'attached' });
await a.$eval('[data-tab="coupons"]', e => e.click()); await a.waitForSelector('.coupon-row');
await a.waitForTimeout(500); await a.screenshot({ path: SP + '/coupons-admin-390.png', fullPage: true });
const ov = await a.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth);
console.log('admin overflow', ov);
const c = await ctx.newPage(); c.on('pageerror', e => errs.push(e.message));
await c.goto(B + '#/restaurant/burger-house'); await c.waitForSelector('[data-add="bh1"]'); await c.click('[data-add="bh1"]'); await c.click('[data-inc="bh1"]');
await c.goto(B + '#/cart'); await c.waitForSelector('#promoInput'); await c.fill('#promoInput', 'arrivo20'); await c.click('#promoForm button'); await c.waitForTimeout(500);
await c.screenshot({ path: SP + '/coupons-cart-390.png', fullPage: true });
console.log('cart bar', await c.evaluate(() => [location.hash, document.querySelector('.mobile-cart-bar').className])); console.log('cart overflow', await c.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth));
console.log('errors', errs); await b.close();
